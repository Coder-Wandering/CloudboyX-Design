interface BlockInstanceOverride {
  settings?: Partial<BlockSettings>;
  content?: Record<string, any>;
}

function createInstance(type: string, overrides: BlockInstanceOverride = {}): BlockInstance {
  const def = BLOCK_DEFINITIONS.find((b) => b.type === type);
  if (!def) {
    throw new Error(`Block definition not found: ${type}`);
  }
  return {
    id: `block-${Math.random().toString(36).substring(2, 9)}`,
    type: def.type,
    category: def.category,
    name: def.name,
    settings: { ...def.defaultSettings, ...(overrides.settings || {}) },
    content: { ...def.defaultContent, ...(overrides.content || {}) },
  };
}

